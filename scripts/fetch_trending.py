"""GitHub Daily Top 10 Rising Stars 报告生成器.

抓取「前一天创建/获得 star 增长」排名前 10 的开源项目，生成中英文双语 Markdown 报告。

策略：GitHub Search API，按 created:>前一天 查询 + sort=stars，
即“前一天新建且 star 数最多的仓库”（爆红新星 / rising stars），
这是唯一能在“昨天”这个时间维度上有客观排序口径的官方 API。
"""

import json
import os
import urllib.request
from datetime import date, timedelta

API_URL = "https://api.github.com/search/repositories"
PER_PAGE = 10
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPORTS_DIR = os.path.join(REPO_ROOT, "reports")

UA = {"User-Agent": "github-trending-daily-bot", "Accept": "application/vnd.github+json"}


def fetch_top_repos(day: date, per_page: int = PER_PAGE):
    q = f"created:{day.isoformat()}"
    params = f"?q={urllib.parse.quote(q)}&sort=stars&order=desc&per_page={per_page}"
    req = urllib.request.Request(API_URL + params, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    return data.get("items", [])


def fmt_num(n: int) -> str:
    return f"{n:,}"


def repo_row(repo, rank: int) -> dict:
    desc = (repo.get("description") or "").strip()
    topics = ", ".join(repo.get("topics", [])[:6]) or "-"
    return {
        "rank": rank,
        "full_name": repo["full_name"],
        "url": repo["html_url"],
        "stars": repo.get("stargazers_count", 0),
        "forks": repo.get("forks_count", 0),
        "watchers": repo.get("subscribers_count", 0) or repo.get("watchers_count", 0),
        "issues": repo.get("open_issues_count", 0),
        "language": repo.get("language") or "-",
        "owner_type": repo.get("owner", {}).get("type", "-"),
        "topics": topics,
        "description": desc,
        "created_at": repo.get("created_at", ""),
    }


def star_comment(stars: int) -> str:
    if stars >= 5000:
        return "现象级爆红 🔥" if False else "Phenomenal 🔥"
    if stars >= 1000:
        return "Highly trending ⭐"
    if stars >= 300:
        return "Rising fast 📈"
    return "Warming up 🌱"


def build_report(day: date, repos) -> tuple[str, str]:
    day_s = day.isoformat()
    next_s = (day + timedelta(days=1)).isoformat()
    gen_time = f"{__import__('datetime').datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}"

    en_rows = []
    zh_rows = []
    for i, r in enumerate(repos, 1):
        row = repo_row(r, i)
        name_link = f"[{row['full_name']}]({row['url']})"
        en_rows.append(
            f"| {i} | {name_link} | ⭐ {fmt_num(row['stars'])} | 🍴 {fmt_num(row['forks'])} | {row['language']} | {star_comment(row['stars'])} |"
        )
        zh_rows.append(
            f"| {i} | {name_link} | ⭐ {fmt_num(row['stars'])} | 🍴 {fmt_num(row['forks'])} | {row['language']} | {star_comment(row['stars'])} |"
        )

    en_details = []
    zh_details = []
    for i, r in enumerate(repos, 1):
        row = repo_row(r, i)
        en_details.append(
            f"### {i}. [{row['full_name']}]({row['url']})\n\n"
            f"- ⭐ Stars: **{fmt_num(row['stars'])}** | 🍴 Forks: **{fmt_num(row['forks'])}** | 👀 Watchers: **{fmt_num(row['watchers'])}** | 🐛 Open issues: **{fmt_num(row['issues'])}**\n"
            f"- 🧠 Language: **{row['language']}** | Owner: {row['owner_type']} | Created: {row['created_at'][:10]}\n"
            f"- 🏷️ Topics: {row['topics']}\n\n"
            f"> {row['description'] or '_No description provided._'}\n"
        )
        zh_details.append(
            f"### {i}. [{row['full_name']}]({row['url']})\n\n"
            f"- ⭐ Star 数：**{fmt_num(row['stars'])}** | 🍴 Fork 数：**{fmt_num(row['forks'])}** | 👀 关注数：**{fmt_num(row['watchers'])}** | 🐛 未关闭 issue：**{fmt_num(row['issues'])}**\n"
            f"- 🧠 主要语言：**{row['language']}** | 归属：{row['owner_type']} | 创建日期：{row['created_at'][:10]}\n"
            f"- 🏷️ 话题标签：{row['topics']}\n\n"
            f"> {row['description'] or '_（仓库未填写简介）_'}\n"
        )

    total_stars = sum(r.get("stargazers_count", 0) for r in repos)
    langs = {}
    for r in repos:
        lang = r.get("language") or "Other"
        langs[lang] = langs.get(lang, 0) + 1
    top_lang = max(langs, key=langs.get) if langs else "-"
    top_repo = repos[0]["full_name"] if repos else "-"

    en = f"""# 🌟 GitHub Daily Top 10 Rising Stars — {day_s}

> Generated at {gen_time} · Data source: [GitHub Search API](https://docs.github.com/en/rest/search)

## 📊 Snapshot

| Metric | Value |
| --- | --- |
| Date | {day_s} |
| Repos listed | {len(repos)} |
| Combined stars | ⭐ {fmt_num(total_stars)} |
| Hottest repo | **{top_repo}** |
| Dominant language | **{top_lang}** |

## 🏆 Top 10 at a glance

| # | Repository | Stars | Forks | Language | Verdict |
| --- | --- | --- | --- | --- | --- |
{chr(10).join(en_rows)}

## 🔍 Repo details

{chr(10).join(en_details)}
---

*Auto-generated by [github-trending-daily]({os.environ.get('REPO_URL', 'https://github.com/liudonghua123/github-trending-daily')}). Next report: {next_s}.*
"""

    zh = f"""# 🌟 GitHub 每日新星榜 Top 10 — {day_s}

> 生成时间：{gen_time} · 数据来源：[GitHub Search API](https://docs.github.com/en/rest/search)

## 📊 今日快照

| 指标 | 数值 |
| --- | --- |
| 统计日期 | {day_s} |
| 上榜仓库数 | {len(repos)} |
| 合计 Star 数 | ⭐ {fmt_num(total_stars)} |
| 最火仓库 | **{top_repo}** |
| 主导语言 | **{top_lang}** |

## 🏆 十强一览

| 排名 | 仓库 | Star | Fork | 语言 | 点评 |
| --- | --- | --- | --- | --- | --- |
{chr(10).join(zh_rows)}

## 🔍 仓库详情

{chr(10).join(zh_details)}
---

*本报告由 [github-trending-daily]({os.environ.get('REPO_URL', 'https://github.com/liudonghua123/github-trending-daily')}) 自动生成。下期报告：{next_s}。*
"""
    return en, zh


def write_report(day: date):
    repos = fetch_top_repos(day)
    if not repos:
        print(f"WARN: no repos found for {day.isoformat()}, report skipped")
        return None
    en, zh = build_report(day, repos)
    os.makedirs(REPORTS_DIR, exist_ok=True)
    en_path = os.path.join(REPORTS_DIR, f"{day.isoformat()}-en.md")
    zh_path = os.path.join(REPORTS_DIR, f"{day.isoformat()}-zh.md")
    with open(en_path, "w", encoding="utf-8") as f:
        f.write(en)
    with open(zh_path, "w", encoding="utf-8") as f:
        f.write(zh)

    # index.json：供前端 web app 拉取报告列表
    index_path = os.path.join(REPORTS_DIR, "index.json")
    entries = []
    if os.path.exists(index_path):
        with open(index_path, "r", encoding="utf-8") as f:
            try:
                entries = json.load(f)
            except Exception:
                entries = []
    entry = {
        "date": day.isoformat(),
        "en": f"reports/{day.isoformat()}-en.md",
        "zh": f"reports/{day.isoformat()}-zh.md",
        "top_repo": repos[0]["full_name"],
        "top_stars": repos[0].get("stargazers_count", 0),
        "total_stars": sum(r.get("stargazers_count", 0) for r in repos),
    }
    entries = [e for e in entries if e["date"] != day.isoformat()]
    entries.append(entry)
    entries.sort(key=lambda e: e["date"], reverse=True)
    with open(index_path, "w", encoding="utf-8") as f:
        json.dump(entries, f, ensure_ascii=False, indent=2)

    print(f"OK report for {day.isoformat()}: {len(repos)} repos, top={entry['top_repo']} (⭐{entry['top_stars']})")
    return en_path, zh_path


if __name__ == "__main__":
    import urllib.parse
    import sys
    import datetime

    # 可选参数指定日期（YYYY-MM-DD），默认昨天（UTC）
    if len(sys.argv) > 1:
        target = datetime.date.fromisoformat(sys.argv[1])
    else:
        target = datetime.datetime.now(datetime.timezone.utc).date() - timedelta(days=1)
    write_report(target)
